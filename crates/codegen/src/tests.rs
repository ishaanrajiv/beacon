/// Runs one type checker over every file, and says what it reported for each: `(file, output)`.
fn report(dir: &Path, program: &str, args: &[&str]) -> String {
    let output = Command::new(program)
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap_or_else(|e| panic!("{program}: {e}"));
    format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )
}

/// The lines of `output` that are errors in `file`.
fn errors_in<'a>(output: &'a str, file: &str) -> Vec<&'a str> {
    output
        .lines()
        .filter(|line| line.contains(file) && line.contains("error"))
        .collect()
}

#[test]
fn generated_python_type_checks_and_misuse_does_not() {
    let Some(npx) = npx() else { return };
    let dir = scratch("python");
    for source in ["backup", "assistant"] {
        write(
            &dir,
            &format!("{source}_kinds.py"),
            &generate(&example(source), Language::Python),
        );
    }
    write(
        &dir,
        "pyrightconfig.json",
        r#"{"pythonVersion": "3.10", "typeCheckingMode": "strict"}"#,
    );
    write(&dir, "good.py", PYTHON_GOOD);
    for (name, _, text) in PYTHON_BAD {
        write(&dir, &format!("bad_{name}.py"), text);
    }
    let output = report(&dir, npx, &["-y", "pyright@1.1.414"]);
    for file in ["good.py", "backup_kinds.py", "assistant_kinds.py"] {
        let errors = errors_in(&output, file);
        assert!(
            errors.is_empty(),
            "{file} should type-check:\n{}",
            errors.join("\n")
        );
    }
    for (name, expected, _) in PYTHON_BAD {
        let errors = errors_in(&output, &format!("bad_{name}.py"));
        assert!(
            errors.iter().any(|e| e.contains(expected)),
            "bad_{name}.py should fail with `{expected}`, and pyright said:\n{}\n\nall output:\n{output}",
            errors.join("\n")
        );
    }
    let _ = std::fs::remove_dir_all(&dir);
}

