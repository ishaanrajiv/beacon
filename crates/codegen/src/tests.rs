/// `npx`, when type checks should run: it is on PATH and BEACON_SKIP_TYPECHECK isn't set
/// (`scripts/check --fast` sets it).
fn npx() -> Option<&'static str> {
    if std::env::var("BEACON_SKIP_TYPECHECK").is_ok_and(|v| v == "1") {
        return None;
    }
    let found = Command::new("npx")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success());
    if found {
        Some("npx")
    } else {
        eprintln!("skipping: npx is not on PATH, so pyright and tsc can't run");
        None
    }
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("beacon-codegen-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display()));
    dir
}

fn write(dir: &Path, name: &str, text: &str) {
    std::fs::write(dir.join(name), text).unwrap_or_else(|e| panic!("{name}: {e}"));
}

