/// The files the client suites import are what `beacon gen` writes now. `BEACON_BLESS=1 cargo
/// test -p beacon-codegen` rewrites them after a change to the generator or a client.
#[test]
fn committed_files_are_current() {
    let bless = std::env::var("BEACON_BLESS").is_ok_and(|v| v == "1");
    let mut stale = Vec::new();
    for source in EXAMPLES {
        let decl = example(source);
        assert!(check(&decl).is_empty(), "{source}: {:?}", check(&decl));
        for language in Language::ALL {
            let path = committed(source, language);
            let text = generate(&decl, language);
            if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
                if bless {
                    if let Some(parent) = path.parent() {
                        let _ = std::fs::create_dir_all(parent);
                    }
                    std::fs::write(&path, &text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
                } else {
                    stale.push(path.display().to_string());
                }
            }
        }
    }
    assert!(
        stale.is_empty(),
        "stale generated files: {stale:?}; run `BEACON_BLESS=1 cargo test -p beacon-codegen` and commit them"
    );
}

#[test]
fn the_header_names_the_source_version_and_hash() {
    let decl = example("backup");
    for language in Language::ALL {
        let text = generate(&decl, language);
        let first = text.lines().next().unwrap_or_default();
        assert!(
            first.contains("Generated by `beacon gen` 0.1.0 from the declarations of `backup`"),
            "{first}"
        );
        assert_eq!(hash_in(&text), Some(hash(&decl).as_str()));
        assert_eq!(
            generate(&decl, language),
            text,
            "the same declarations give the same text"
        );
    }
}

#[test]
fn the_hash_follows_what_is_published_not_the_layout() {
    let a = parse(
        r#"source = "backup"
name = "Backups"
[kinds."backup.done"]
class = "record"
title = "Backup finished"
"#,
    );
    let b = parse(
        r#"# a comment
name = "Backups"
source = "backup"

[kinds."backup.done"]
title = "Backup finished"
class = "record"
"#,
    );
    let c = parse(
        r#"source = "backup"
name = "Backups"
[kinds."backup.done"]
class = "record"
title = "Backup done"
"#,
    );
    assert_eq!(hash(&a), hash(&b));
    assert_ne!(hash(&a), hash(&c));
    assert_eq!(hash(&a).len(), 16);
}

#[test]
fn python_signatures_follow_the_spec() {
    let text = generate(&example("backup"), Language::Python);
    assert!(text.starts_with("# Generated by `beacon gen`"));
    assert!(text.contains("from __future__ import annotations\n\nimport json\n"));
    assert!(text.contains(
        "def backup_failed(\n    *,\n    last_ok: int | datetime,\n    reason: str,\n    key: str = \"\",\n    labels: Mapping[str, str] | None = None,\n    url: str | None = None,\n) -> Sent:\n    \"\"\"The last backup run failed.\"\"\"\n"
    ));
    assert!(text.contains("facts=_beacon.present({\"last_ok\": _beacon.time_ms(last_ok)}),"));
    assert!(text.contains("def backup_failed_resolved(\n    *,\n    key: str = \"\",\n) -> Sent:"));
    assert!(text.contains("def backup_failed_entry(\n"));
    // A record has neither companion, and no url without `open`.
    assert!(text.contains("def backup_finished(\n    *,\n    size: str,\n    took: int | timedelta,\n    key: str = \"\",\n    labels: Mapping[str, str] | None = None,\n) -> Sent:"));
    assert!(!text.contains("backup_finished_resolved"));
    assert!(text.contains("SnapshotKind = Literal[\"backup.failed\", \"backup.space\", \"backup.stale\"]"));
    assert!(text.contains("def unobserved(reason: str, *, stale_after: str | None = None) -> Sent:"));
}

#[test]
fn context_kinds_take_a_context() {
    let decl = example("assistant");
    let python = generate(&decl, Language::Python);
    assert!(python.contains(
        "def assistant_approval(\n    *,\n    thread: str,\n    question: str,\n    context: str,\n"
    ));
    assert!(
        python
            .contains("def assistant_approval_resolved(\n    *,\n    context: str,\n    key: str = \"\",\n")
    );
    let ts = generate(&decl, Language::TypeScript);
    assert!(ts.contains(
        "export function assistantApproval(args: { thread: string; question: string; context: string; url?: string } & Common): Promise<Sent> {"
    ));
    assert!(ts.contains(
        "export function assistantApprovalResolved(args: { context: string; key?: string }): Promise<Sent> {"
    ));
    // A kind with nothing to send can be called with no argument.
    assert!(!ts.contains("(args: Common)"));
}

