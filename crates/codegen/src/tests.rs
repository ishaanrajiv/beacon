use crate::{Language, check, generate, hash, hash_in, python, runtime, typescript};
use beacon_core::decl::{self, Check, Declarations};
use std::path::{Path, PathBuf};
use std::process::Command;

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn example(source: &str) -> Declarations {
    let path = root().join("examples/homelab-ish").join(source).join("beacon");
    match decl::load(&path, &Check::default()) {
        Ok(decl) => decl,
        Err(problems) => panic!("{source}: {problems:?}"),
    }
}

const EXAMPLES: [&str; 3] = ["assistant", "backup", "ship"];

fn parse(text: &str) -> Declarations {
    match decl::parse(text, &Check::default()) {
        Ok(decl) => decl,
        Err(problems) => panic!("{problems:?}"),
    }
}

/// Where the committed generated files live: the client suites import them.
fn committed(source: &str, language: Language) -> PathBuf {
    match language {
        Language::Python => root().join(format!("clients/python/tests/gen/{source}_kinds.py")),
        Language::TypeScript => root().join(format!("clients/node/tests/gen/{source}_kinds.ts")),
    }
}

#[test]
fn both_clients_have_their_runtime_markers() {
    let python = runtime(crate::PYTHON_CLIENT);
    assert!(python.starts_with("import json"), "{python:.80}");
    assert!(python.contains("_beacon = _Runtime()"));
    assert!(
        !python.contains("def send("),
        "the standalone functions stay out of generated files"
    );
    let typescript = runtime(crate::TYPESCRIPT_CLIENT);
    assert!(
        typescript.starts_with("export const DEFAULT_URL"),
        "{typescript:.80}"
    );
    assert!(typescript.contains("const beacon = new BeaconRuntime();"));
    assert!(!typescript.contains("export function send("));
}

